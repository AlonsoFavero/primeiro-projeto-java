package fundamentos.sobrecarga;

public class Calculadora {

    public double somar(double numero1 , double numero2){

        return numero1 + numero2;
    }

    public int somar(int numero8, int numero9){

        return numero8 + numero9;
    }

    public int somar(int numero3 , int numero4 , int numero5){

        return numero3 + numero4 + numero5;
    }

}
