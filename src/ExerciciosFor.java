public class ExerciciosFor {

    public static void main(String[] args) {

        // Contando de 1 até 5
        for (int i = 1; i <= 5; i++) {
            System.out.println(i);
        }

        // Contando de 1 até 10
        for (int i = 1; i <= 10; i++) {
            System.out.println(i);
        }

        // Mostrando números pares
        for (int i = 1; i <= 10; i++) {
            if (i % 2 == 0) {
                System.out.println(i);
            }
        }

        // Multiplicando os números por 5
        for (int i = 1; i <= 10; i++) {
            System.out.println(i * 5);
        }
    }
}